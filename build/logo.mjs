// The product mark, written into site/public/logo.svg and build/icon.svg.
//
// The artwork is vector from the start: a cargo ship, its containers and two waves on a navy
// rounded square, plus a "Free Harbor" wordmark under them. The wordmark is not carried here,
// because every place the mark appears already sets the name beside it in its own type (the site
// header, the social card, the tray's About band), and a 16px icon cannot hold text anyway.
//
// Not part of any build, for the same reason build/icon.mjs is not: the outputs are committed, and
// a build that needs Node to produce a Windows resource is a build that fails on a machine with
// only the .NET SDK. This exists so the two SVGs have a provenance that can be re-run when the
// artwork changes, rather than being files nobody can regenerate.
//
//   node build/logo.mjs       # from the repository root
//   node build/icon.mjs       # the .ico reads what this wrote

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

const SIZE = 1254;

// The symbol's own box inside the original 1254 square, measured off the paths below: the
// containers' top at y=322, the lower wave's foot at y=808. Centring on this box rather than on
// the square is what removing the wordmark needs, since the symbol was placed to leave it room.
const SYMBOL = { cx: 626, cy: 565 };

// Ids are prefixed because og-card.mjs inlines the mark's children into a card that has gradients
// of its own, and two elements answering to one id is a fill that depends on document order.
const symbol = ({ porthole, cyan, navy }) => `
    <!-- containers -->
    <g fill="${cyan}">
      <path d="M559 366 Q559 359 567 357 L694 324 Q700 322 706 325 L748 343 Q756 346 756 355 L756 438 L699 423 L559 455 Z"/>
      <path d="M423 474 Q423 470 429 468 L531 448 Q537 447 537 453 L537 540 L423 560 Z"/>
      <path d="M559 475 L678 452 L678 537 Q678 543 672 544 L559 554 Z"/>
      <path d="M699 443 L802 468 Q809 470 809 477 L809 490 L699 516 Z"/>
    </g>
    <!-- hull -->
    <path fill="#fff" d="M392 580 L665 571 Q686 570 703 555 L897 484 Q915 477 924 491 Q929 500 923 512 L857 663 Q848 685 823 691 Q785 700 746 684 L623 630 Q548 597 478 604 L392 620 Z"/>${
      porthole ? `\n    <circle cx="833" cy="561" r="21" fill="${navy}"/>` : ""
    }
    <!-- waves -->
    <path fill="${cyan}" d="M328 714 Q405 620 497 630 Q571 636 644 671 Q755 724 860 696 Q827 739 765 750 Q696 765 615 730 Q504 681 430 681 Q371 681 328 714 Z"/>
    <path fill="${cyan}" d="M388 758 Q443 710 499 715 Q558 718 622 749 Q700 787 766 778 Q720 808 658 808 Q594 808 531 778 Q454 742 420 751 Z"/>`;

const placed = (scale) =>
  `translate(${SIZE / 2} ${SIZE / 2}) scale(${scale}) translate(${-SYMBOL.cx} ${-SYMBOL.cy})`;

const mark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" role="img" aria-label="FreeHarbor">
  <!-- The product mark.
       Generated by build/logo.mjs. Edit the artwork there, not this. -->
  <defs>
    <linearGradient id="fh-bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#073b9c"/>
      <stop offset="1" stop-color="#002d83"/>
    </linearGradient>
    <linearGradient id="fh-cyan" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0" stop-color="#149ff0"/>
      <stop offset="1" stop-color="#21b8f5"/>
    </linearGradient>
  </defs>
  <rect width="${SIZE}" height="${SIZE}" rx="225" fill="url(#fh-bg)"/>
  <g transform="${placed(1.45)}">${symbol({ porthole: true, cyan: "url(#fh-cyan)", navy: "#073b9c" })}
  </g>
</svg>
`;

// Below 48px a gradient across a 10px container is one colour anyway, and the porthole is less
// than a pixel, so the small entries drop both and give the symbol more of the square.
const small = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" role="img" aria-label="FreeHarbor">
  <!-- The mark at tray sizes: flat colours, no porthole, a larger symbol.
       Generated by build/logo.mjs. Edit the artwork there, not this. -->
  <rect width="${SIZE}" height="${SIZE}" rx="225" fill="#073b9c"/>
  <g transform="${placed(1.85)}">${symbol({ porthole: false, cyan: "#21b8f5", navy: "#073b9c" })}
  </g>
</svg>
`;

for (const [path, svg] of [
  [join(root, "site", "public", "logo.svg"), mark],
  [join(root, "build", "icon.svg"), small],
]) {
  writeFileSync(path, svg);
  console.log(`${path}  ${svg.length} bytes`);
}
